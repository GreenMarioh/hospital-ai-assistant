"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import { useState } from "react";
import { AuthFrame } from "@/components/AuthFrame";
import { Alert, Button, Field } from "@/components/ui";
import { HOME, errorMessage } from "@/lib/api";
import { useAuth } from "@/lib/auth";

export default function LoginPage() {
  const { login, verifyMfaLogin } = useAuth();
  const router = useRouter();
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [mfaTicket, setMfaTicket] = useState<string | null>(null);
  const [mfaCode, setMfaCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      if (mfaTicket) {
        const user = await verifyMfaLogin(mfaTicket, mfaCode);
        router.replace(HOME[user.role]);
      } else {
        const res = await login(email, password);
        if (res.mfa_required && res.mfa_ticket) {
          setMfaTicket(res.mfa_ticket);
          setBusy(false);
          return;
        }
        if (res.user) {
          router.replace(HOME[res.user.role]);
        }
      }
    } catch (err) {
      setError(errorMessage({ detail: (err as Error).message }));
      setBusy(false);
    }
  }

  function resetToPassword() {
    setMfaTicket(null);
    setMfaCode("");
    setError(null);
  }

  return (
    <AuthFrame>
      <h1 className="page-title">{mfaTicket ? "Two-factor authentication" : "Sign in"}</h1>
      <p className="mb-8 mt-2 text-[15px] text-slate-600">
        {mfaTicket ? "One more step to reach your account." : "Use the email and password for your account."}
      </p>
      <div>
        <form onSubmit={submit} className="space-y-4">
          {error && <Alert kind="error">{error}</Alert>}
          {mfaTicket ? (
            <>
              <p className="text-sm text-slate-600">
                Enter the 6-digit verification code generated by your authenticator app.
              </p>
              <Field
                label="Authentication code"
                type="text"
                inputMode="numeric"
                autoComplete="one-time-code"
                maxLength={6}
                required
                placeholder="123456"
                value={mfaCode}
                onChange={(e) => setMfaCode(e.target.value)}
              />
              <Button type="submit" disabled={busy} className="w-full">
                {busy ? "Verifying…" : "Verify code"}
              </Button>
              <button
                type="button"
                onClick={resetToPassword}
                className="link mt-2 w-full text-center text-sm"
              >
                Back to password sign-in
              </button>
            </>
          ) : (
            <>
              <Field
                label="Email"
                type="email"
                autoComplete="username"
                required
                value={email}
                onChange={(e) => setEmail(e.target.value)}
              />
              <Field
                label="Password"
                type="password"
                autoComplete="current-password"
                required
                value={password}
                onChange={(e) => setPassword(e.target.value)}
              />
              <Button type="submit" disabled={busy} className="w-full">
                {busy ? "Signing in…" : "Sign in"}
              </Button>
            </>
          )}
        </form>
      </div>
      {!mfaTicket && (
        <div className="mt-5 space-y-6 text-sm">
          <p className="text-right">
            <Link className="link" href="/forgot-password">
              Forgot password?
            </Link>
          </p>
          <p className="border-t border-line pt-6 text-slate-700">
            New patient?{" "}
            <Link className="link" href="/register">
              Create an account
            </Link>
          </p>
        </div>
      )}
    </AuthFrame>
  );
}
